"""
Executable checks for the formal properties of PAM-Proof (via ``pam_api``).

A  Correctness          honest Open(F) with F_r subset of F verifies.
B  Opening binding      a Merkle position cannot be accepted with a different
                        (field ID, value) under the same rho.
C  Predicate completeness  any opening missing a required operand fails, even
                        when its Merkle proof is authentic.
D  Projection soundness evaluating P_r on the verified projection gives the same
                        decision (truth value, failed atoms, derived outputs) as
                        evaluating P_r on the full committed layout, for the same
                        evidence; removing any operand yields ``missing_operand``
                        (no defaults).

Randomness (``random.Random(seed)``) only selects cases and mutations; keys are
generated by the OS CSPRNG.
"""

from __future__ import annotations

import random
from dataclasses import replace
from decimal import Decimal
from typing import Any

from .canonical import ENUM_TABLES, TypeTag
from .minimality import evidence_variants, session_context
from .pam import CompletenessPolicy, verify_opening
from .pam_api import Commit, Open, Select, Setup, Verify
from .predicates import PREDICATES, evaluate
from .schema import LAYOUT_V1, REGISTRY

REASONS = tuple(PREDICATES)


def build_contexts(specs, profile_name: str = "C0") -> list[tuple[Any, Any, tuple]]:
    from .profiles import PROFILES
    from .protocol import DvasEnvironment

    env = DvasEnvironment(profile=PROFILES[profile_name])
    out = []
    for sp in specs:
        s = env.session(sp)
        s.commit(); assert s.authorize().ok; assert s.open_session().ok
        s.deliver(); assert s.submit_receipt().ok
        out.append((env, s, session_context(env, s)))
    return out


def _row(prop: str, reason: str, trials: int, passed: int, detail: str = "") -> dict:
    return {"property": prop, "reason": reason, "trials": trials, "passed": passed, "failed": trials - passed,
            "holds": trials == passed and trials > 0, "detail": detail}


def _other_value(name: str, v: Any, rng: random.Random) -> Any:
    spec = REGISTRY.spec(name)
    if spec.type_tag == TypeTag.ENUM:
        alts = [x for x in ENUM_TABLES[spec.enum_table] if x != v]
        return rng.choice(alts) if alts else None
    if spec.type_tag == TypeTag.FIXED6:
        return v + Decimal(rng.randint(1, 10**6)) / Decimal(10**6)
    if spec.type_tag == TypeTag.TIMESTAMP:
        return v + rng.randint(1, 10**6)
    if v is None:
        return "x"
    return str(v) + rng.choice(["0", "a", " ", "_"])


def check_correctness(contexts, rng: random.Random, extra_trials: int = 5) -> list[dict]:
    pp = Setup(LAYOUT_V1)
    rows = []
    for r in REASONS:
        req = Select(pp, r)
        others = [n for n in LAYOUT_V1.field_names if n not in req]
        trials = passed = 0
        for _, s, _ in contexts:
            for k in range(extra_trials + 1):
                F = list(req) + (rng.sample(others, rng.randint(0, len(others))) if k else [])
                rho, st = s.commitment.rho_t, s.commitment
                pi = Open(pp, st, F, r=r)
                trials += 1
                passed += Verify(pp, rho, r, pi).ok
        rows.append(_row("A_correctness", r, trials, passed, "F = F_r plus random extra committed fields"))
    return rows


def check_binding(contexts, rng: random.Random, trials_per_reason: int = 40) -> list[dict]:
    pp = Setup(LAYOUT_V1)
    rows = []
    for r in REASONS:
        trials = passed = 0
        for _ in range(trials_per_reason):
            _, s, _ = rng.choice(contexts)
            pi = Open(pp, s.commitment, Select(pp, r), r=r)
            fields = dict(pi.fields)
            fid = rng.choice(list(fields))
            name = REGISTRY.spec(fid).name
            mode = rng.choice(["value", "field_id", "both"])
            if mode == "value":
                alt = _other_value(name, fields[fid], rng)
                if alt is None:
                    continue
                fields[fid] = alt
            else:
                same_type = [n for n in LAYOUT_V1.field_names if n != name and REGISTRY.spec(n).type_tag ==
                             REGISTRY.spec(name).type_tag and REGISTRY.spec(n).field_id not in fields]
                if not same_type:
                    continue
                new = REGISTRY.spec(rng.choice(same_type)).field_id
                val = fields.pop(fid)
                fields[new] = val if mode == "field_id" else _other_value(REGISTRY.spec(new).name, val, rng) or val
            forged = replace(pi, fields=tuple(sorted(fields.items())))
            # authenticity alone (completeness disabled) must already reject
            res = verify_opening(s.commitment.rho_t, forged, reason=r, check_completeness=False)
            trials += 1
            passed += not res.ok
        rows.append(_row("B_opening_binding", r, trials, passed,
                         "substituted value / field ID / both at an opened position; Merkle-only verifier must reject"))
    # injectivity of the canonical leaf pre-image
    from .schema import encode_leaf

    seen, collisions, n = {}, 0, 0
    for name in LAYOUT_V1.field_names:
        for _, s, _ in contexts:
            v = s.commitment.values[name]
            for val in (v, _other_value(name, v, rng)):
                if val is None:
                    continue
                pre = encode_leaf(LAYOUT_V1, name, val)
                n += 1
                if pre in seen and seen[pre] != (name, str(val)):
                    collisions += 1
                seen[pre] = (name, str(val))
    rows.append(_row("B_leaf_encoding_injective", "*", n, n - collisions, "distinct (field, value) -> distinct leaf pre-image"))
    return rows


def check_completeness(contexts, rng: random.Random, random_subsets: int = 10) -> list[dict]:
    pp = Setup(LAYOUT_V1)
    rows = []
    for r in REASONS:
        req = list(Select(pp, r))
        others = [n for n in LAYOUT_V1.field_names if n not in req]
        trials = passed = authentic = 0
        for _, s, _ in contexts:
            cases = [[n for n in req if n != f] for f in req]  # every single omission
            for _ in range(random_subsets):  # random proper subsets, optionally padded with irrelevant fields
                k = rng.randint(0, len(req) - 1)
                cases.append(rng.sample(req, k) + rng.sample(others, rng.randint(0, len(others))))
            for F in cases:
                if not F:
                    continue
                pi = Open(pp, s.commitment, F, r=r)
                trials += 1
                res = Verify(pp, s.commitment.rho_t, r, pi)
                passed += (not res.ok) and res.code == "INCOMPLETE_OPENING"
                authentic += verify_opening(s.commitment.rho_t, pi, reason=r, check_completeness=False).ok
        rows.append(_row("C_predicate_completeness", r, trials, passed,
                         f"authentic-but-incomplete openings; Merkle-only verifier accepted {authentic}/{trials}"))
    # EXACT policy rejects extra fields
    ppx = Setup(LAYOUT_V1, policy=CompletenessPolicy.EXACT)
    t = p = 0
    for r in REASONS:
        req = list(Select(ppx, r))
        extra = [n for n in LAYOUT_V1.field_names if n not in req]
        for _, s, _ in contexts[:3]:
            if not extra:
                continue
            pi = Open(ppx, s.commitment, req + [rng.choice(extra)], r=r)
            t += 1
            p += Verify(ppx, s.commitment.rho_t, r, pi).code == "NON_EXACT_OPENING"
    rows.append(_row("C_exact_policy", "*", t, p, "EXACT mode rejects F(pi) != F_r"))
    return rows


def _random_evidence(ev: dict, c: dict, rng: random.Random) -> dict:
    e = dict(ev)
    pick = rng.choice(["kwh", "ts", "tariff", "limits", "binding", "auth", "none"])
    if pick == "auth":  # authorization-request evidence
        k = rng.choice(["request_user_id", "request_user_account", "request_paytok", "request_tid", "available_balance"])
        if k == "available_balance":
            e[k] = (c["preauth_limit"] * Decimal(rng.uniform(0, 2))).quantize(Decimal("0.000001"))
        else:
            e[k] = rng.choice([e[k], str(e[k]) + "_other"])
    if pick == "kwh":
        e["delivered_kwh"] = (c["cap_kwh"] * Decimal(rng.uniform(0, 2))).quantize(Decimal("0.000001"))
    elif pick == "ts":
        e["ts_start"] = c["tw_start"] + rng.randint(-7200, 7200)
        e["ts_end"] = c["tw_end"] + rng.randint(-7200, 7200)
    elif pick == "tariff":
        e["applied_tariff_version"] = rng.choice([c["tariff_version"], c["tariff_version"] + "x"])
    elif pick == "limits":
        lim = (c["preauth_limit"] * Decimal(rng.uniform(0.2, 2))).quantize(Decimal("0.000001"))
        e["effective_limit"], e["held_amount"] = lim, lim
    elif pick == "binding":
        e["receipt_meter_id"] = rng.choice([e["receipt_meter_id"], "M_OTHER"])
        e["receipt_tid"] = rng.choice([e["receipt_tid"], "T_OTHER"])
    return e


def check_projection_soundness(contexts, rng: random.Random, evidence_per_context: int = 12) -> list[dict]:
    pp = Setup(LAYOUT_V1)
    rows = []
    for r in REASONS:
        pred = PREDICATES[r]
        trials = passed = true_cases = false_cases = 0
        nodefault_t = nodefault_p = 0
        for _, s, (c, ev, rel) in contexts:
            pi = Open(pp, s.commitment, Select(pp, r), r=r)
            vr = Verify(pp, s.commitment.rho_t, r, pi)
            assert vr.ok
            projected = dict(vr.values)
            evs = evidence_variants(pred, c, ev, rel) + [_random_evidence(ev, c, rng) for _ in range(evidence_per_context)]
            for e in evs:
                full = evaluate(pred, c, e, rel)
                proj = evaluate(pred, projected, e, rel)
                trials += 1
                same = (full.ok, full.failed, full.missing, full.outputs) == (proj.ok, proj.failed, proj.missing, proj.outputs)
                passed += same
                true_cases += full.ok
                false_cases += not full.ok
            for f in Select(pp, r):  # removing any verified operand never falls back to a default
                res = evaluate(pred, {k: v for k, v in projected.items() if k != f}, ev, rel)
                nodefault_t += 1
                nodefault_p += (not res.ok) and f"committed:{f}" in res.missing
        rows.append(_row("D_projection_soundness", r, trials, passed,
                         f"identical decision on full layout vs verified projection; P true in {true_cases}, false in {false_cases}"))
        rows.append(_row("D_no_default_substitution", r, nodefault_t, nodefault_p,
                         "projection minus any operand -> missing_operand, never a default"))
    return rows


def run_all(contexts, seed: int = 20261006, scale: int = 1) -> list[dict]:
    rng = random.Random(seed)
    return (check_correctness(contexts, rng, 5 * scale) + check_binding(contexts, rng, 40 * scale)
            + check_completeness(contexts, rng, 10 * scale) + check_projection_soundness(contexts, rng, 12 * scale))
